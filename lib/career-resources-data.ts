export type ResourceFilters = {
  query: string;
  category: string;
  region: string;
  audience: string;
  organization: string;
};

/** Search all displayed facts; each query word must match somewhere in the record. */
export function filterCareerResources(
  entries: readonly CareerResource[],
  filters: ResourceFilters,
): CareerResource[] {
  const normalize = (value: string) =>
    value
      .normalize("NFKD")
      .replace(/[\u0300-\u036f]/g, "")
      .toLowerCase();
  const terms = normalize(filters.query.trim()).split(/\s+/).filter(Boolean);
  return entries.filter((resource) => {
    if (filters.category && resource.category !== filters.category)
      return false;
    if (filters.region && resource.region !== filters.region) return false;
    if (filters.organization && resource.organization !== filters.organization)
      return false;
    if (filters.audience === "youth" && !resource.youthFocused) return false;
    if (filters.audience === "general" && resource.youthFocused) return false;
    const searchable = normalize(
      [
        resource.title,
        resource.organization,
        resource.category,
        resource.description,
        resource.region,
        resource.audienceNote,
        resource.format,
      ].join(" "),
    );
    return terms.every((term) => searchable.includes(term));
  });
}

/** Works for the normal site and the file/GitHub Pages hash-routed edition. */
export function resourceTopicFromLocation(
  search: string,
  hash: string,
): ResourceCategory | null {
  try {
    if (readStaticLocation(hash).section === "youtube-resources")
      return "YouTube learning";
    const staticQuery = hash.startsWith("#/")
      ? new URL(hash.slice(1), "https://static.hire.invalid").searchParams
      : new URLSearchParams();
    const topic =
      staticQuery.get("resourceTopic") ||
      new URLSearchParams(search).get("resourceTopic");
    return resourceCategories.find((category) => category === topic) || null;
  } catch {
    return null;
  }
}
